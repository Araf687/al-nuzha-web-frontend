// ── Exports ───────────────────────────────────────────────────────────
export const translations = { en, ar };
export type Translations  = typeof en;

type LangContextType = { lang: Lang; setLang: (l: Lang) => void; tx: Translations };

const LangContext = createContext<LangContextType>({ lang: "en", setLang: () => {}, tx: en });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = localStorage.getItem("alnuzha_lang") as Lang;
    if (stored === "en" || stored === "ar") {
      setLangState(stored);
      document.documentElement.dir  = stored === "ar" ? "rtl" : "ltr";
      document.documentElement.lang = stored;
    }
  }, []);

  function setLang(l: Lang) {
    setLangState(l);
    localStorage.setItem("alnuzha_lang", l);
    document.documentElement.dir  = l === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = l;
  }

  return (
    <LangContext.Provider value={{ lang, setLang, tx: translations[lang] }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() { return useContext(LangContext); }
